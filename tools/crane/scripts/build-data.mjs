// Bundle crane JSON (data/src/*.json) into lazily loadable scripts for the static page.
//   node tools/crane/scripts/build-data.mjs
// Output: data/index.js (list + summary of every model) and data/models/<id>.js (full data, loaded on demand).
// Script files (not fetch) so the page also works when opened directly from disk (file://).
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'data', 'src');
const outDir = join(root, 'data', 'models');
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const files = readdirSync(srcDir).filter((f) => f.endsWith('.json')).sort();
const index = [];
for (const f of files) {
  const d = JSON.parse(readFileSync(join(srcDir, f), 'utf8'));
  if (!/^[a-z0-9-]+$/.test(d.id)) throw new Error(`bad id in ${f}: ${d.id}`);
  writeFileSync(join(outDir, `${d.id}.js`), `window.CRANE_MODEL_LOADED(${JSON.stringify(d)});\n`);
  const allL = [...new Set(d.boomCharts.flatMap((c) => c.cols.map((k) => k.L)))].sort((a, b) => a - b);
  index.push({
    id: d.id, maker: d.maker, model: d.model, nickname: d.nickname || '', generation: d.generation || '',
    classTon: d.classTon, status: d.status, variant: d.variant || '',
    maxLoad: d.maxLoad || null, boom: { min: d.boom.min, max: d.boom.max }, boomLengths: allL,
    hasJib: !!(d.jibCharts && d.jibCharts.length),
    hasFront: d.boomCharts.some((c) => c.zone === 'front'),
    hasOnTire: !!(d.onTire && d.onTire.length),
    outriggers: d.outriggers.states.map((s) => s.width),
    vehicle: d.vehicle,
    verified: d.verification && d.verification.status,
  });
}
index.sort((a, b) => a.classTon - b.classTon || a.maker.localeCompare(b.maker) || a.model.localeCompare(b.model));
writeFileSync(join(root, 'data', 'index.js'),
  `// generated by scripts/build-data.mjs — do not edit by hand\nwindow.CRANE_INDEX = ${JSON.stringify(index, null, 1)};\n`);
console.log(`${files.length} models -> data/index.js, data/models/*.js`);
